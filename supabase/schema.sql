-- ── Tables ────────────────────────────────────────────────────────────────────

CREATE TABLE folders (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  name        TEXT NOT NULL,
  created_at  TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE TABLE docs (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  folder_id   UUID REFERENCES folders(id) ON DELETE SET NULL,
  type        TEXT NOT NULL CHECK (type IN ('handoff','installation','account-setup')),
  title       TEXT NOT NULL DEFAULT '',
  content     JSONB NOT NULL DEFAULT '{"type":"doc","content":[{"type":"paragraph"}]}',
  icon        JSONB,
  created_at  TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  updated_at  TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE TABLE image_blocks (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  doc_id        UUID REFERENCES docs(id) ON DELETE CASCADE NOT NULL,
  user_id       UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  storage_path  TEXT NOT NULL,
  annotations   JSONB NOT NULL DEFAULT '[]',
  created_at    TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- One active share record per doc or folder.
-- token = share link identifier (view or edit permission).
CREATE TABLE shares (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id        UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  resource_type   TEXT NOT NULL CHECK (resource_type IN ('doc','folder')),
  resource_id     UUID NOT NULL,
  permission      TEXT NOT NULL DEFAULT 'view' CHECK (permission IN ('view','edit')),
  -- Token is generated by the application (base64url via Web Crypto API).
  -- PostgreSQL's encode() doesn't support 'base64url', so no DB default here.
  token           TEXT UNIQUE NOT NULL,
  created_at      TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- ── Indexes ───────────────────────────────────────────────────────────────────

CREATE INDEX ON docs(user_id);
CREATE INDEX ON docs(folder_id);
CREATE INDEX ON docs(updated_at DESC);
CREATE INDEX ON folders(user_id);
CREATE INDEX ON image_blocks(doc_id);
CREATE INDEX ON shares(resource_id);
CREATE INDEX ON shares(token);

-- ── Row-level security ────────────────────────────────────────────────────────

ALTER TABLE folders      ENABLE ROW LEVEL SECURITY;
ALTER TABLE docs         ENABLE ROW LEVEL SECURITY;
ALTER TABLE image_blocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE shares       ENABLE ROW LEVEL SECURITY;

-- folders: owners only
CREATE POLICY "folders_owner" ON folders FOR ALL
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

-- docs: owner full access
CREATE POLICY "docs_owner" ON docs FOR ALL
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

-- docs: a logged-in user who arrives via an edit share can update
-- (the claim_edit_share RPC converts a token into a share record)
CREATE POLICY "docs_claimed_edit" ON docs FOR UPDATE
  USING (
    EXISTS (
      SELECT 1 FROM shares
      WHERE resource_type = 'doc'
        AND resource_id = docs.id
        AND permission = 'edit'
        AND owner_id != auth.uid()
        -- We identify the claimer by storing their user_id in a separate
        -- doc_editors table; see claim_edit_share() below.
    )
  );

-- image_blocks: owner full access
CREATE POLICY "image_blocks_owner" ON image_blocks FOR ALL
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

-- shares: only the owner manages their shares
CREATE POLICY "shares_owner" ON shares FOR ALL
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

-- ── doc_editors (maps edit-share claimers to docs) ────────────────────────────

CREATE TABLE doc_editors (
  doc_id    UUID REFERENCES docs(id) ON DELETE CASCADE NOT NULL,
  user_id   UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  PRIMARY KEY (doc_id, user_id)
);
ALTER TABLE doc_editors ENABLE ROW LEVEL SECURITY;

CREATE POLICY "doc_editors_select" ON doc_editors FOR SELECT
  USING (user_id = auth.uid());

-- Allow the claim_edit_share() function (SECURITY DEFINER) to insert.

-- Update docs_claimed_edit policy to use doc_editors:
DROP POLICY "docs_claimed_edit" ON docs;
CREATE POLICY "docs_claimed_edit" ON docs FOR UPDATE
  USING (
    EXISTS (
      SELECT 1 FROM doc_editors
      WHERE doc_id = docs.id AND user_id = auth.uid()
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM doc_editors
      WHERE doc_id = docs.id AND user_id = auth.uid()
    )
  );

-- Also allow SELECT for claimed editors:
CREATE POLICY "docs_claimed_select" ON docs FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM doc_editors
      WHERE doc_id = docs.id AND user_id = auth.uid()
    )
  );

-- Allow claimed editors to read image_blocks:
CREATE POLICY "image_blocks_editor" ON image_blocks FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM doc_editors
      WHERE doc_id = image_blocks.doc_id AND user_id = auth.uid()
    )
  );

-- ── updated_at trigger ────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = NOW(); RETURN NEW; END;
$$;

CREATE TRIGGER docs_updated_at BEFORE UPDATE ON docs
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ── get_shared_resource(token) ────────────────────────────────────────────────
-- Called by anonymous users to view a shared doc.
-- SECURITY DEFINER bypasses RLS.

CREATE OR REPLACE FUNCTION get_shared_resource(p_token TEXT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_share shares%ROWTYPE;
  v_result JSONB;
BEGIN
  SELECT * INTO v_share FROM shares WHERE token = p_token;
  IF NOT FOUND THEN RETURN NULL; END IF;

  IF v_share.resource_type = 'doc' THEN
    SELECT jsonb_build_object(
      'permission',    v_share.permission,
      'resource_type', 'doc',
      'doc',           to_jsonb(d),
      'image_blocks',  COALESCE((
        SELECT jsonb_agg(to_jsonb(ib))
        FROM image_blocks ib WHERE ib.doc_id = d.id
      ), '[]'::jsonb)
    ) INTO v_result
    FROM docs d WHERE d.id = v_share.resource_id;
  ELSE
    SELECT jsonb_build_object(
      'permission',    v_share.permission,
      'resource_type', 'folder',
      'folder',        to_jsonb(f),
      'docs',          COALESCE((
        SELECT jsonb_agg(
          to_jsonb(d) || jsonb_build_object(
            'image_blocks', COALESCE((
              SELECT jsonb_agg(to_jsonb(ib))
              FROM image_blocks ib WHERE ib.doc_id = d.id
            ), '[]'::jsonb)
          )
        )
        FROM docs d WHERE d.folder_id = v_share.resource_id
      ), '[]'::jsonb)
    ) INTO v_result
    FROM folders f WHERE f.id = v_share.resource_id;
  END IF;

  RETURN v_result;
END;
$$;

GRANT EXECUTE ON FUNCTION get_shared_resource(TEXT) TO anon, authenticated;

-- ── claim_edit_share(token) ───────────────────────────────────────────────────
-- A logged-in user calls this to gain edit access via a share link.

CREATE OR REPLACE FUNCTION claim_edit_share(p_token TEXT)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_share shares%ROWTYPE;
BEGIN
  SELECT * INTO v_share FROM shares
  WHERE token = p_token AND permission = 'edit';

  IF NOT FOUND THEN RETURN FALSE; END IF;
  IF v_share.resource_type != 'doc' THEN RETURN FALSE; END IF;
  -- Don't add the owner as an editor
  IF v_share.owner_id = auth.uid() THEN RETURN TRUE; END IF;

  INSERT INTO doc_editors (doc_id, user_id)
  VALUES (v_share.resource_id, auth.uid())
  ON CONFLICT DO NOTHING;

  RETURN TRUE;
END;
$$;

GRANT EXECUTE ON FUNCTION claim_edit_share(TEXT) TO authenticated;

